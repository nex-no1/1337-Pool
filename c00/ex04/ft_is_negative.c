#include <unistd.h>

void	ft_is_negative(int n)
{
	char	f;
	char	p;

	if (n < 0)
	{
		f = 'N';
		write(1, &f, 1);
	}
	else
	{
		p = 'P';
		write(1, &p, 1);
	}
}
